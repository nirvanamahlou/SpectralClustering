import numpy as np
import matplotlib.pyplot as plt
from sklearn.mixture import GaussianMixture
from sklearn.metrics import silhouette_score
from scipy.linalg import eigh
from sklearn.datasets import make_blobs

def construct_gaussian_affinity_matrix(data, sigma=1.0):
    n_samples = data.shape[0]
    affinity_matrix = np.zeros((n_samples, n_samples))
    for i in range(n_samples):
        for j in range(n_samples):
            distance = np.linalg.norm(data[i] - data[j])
            affinity_matrix[i, j] = np.exp(-distance**2 / (2 * sigma**2))
    return affinity_matrix

def normalize_affinity_matrix(affinity_matrix):
    D = np.diag(np.sum(affinity_matrix, axis=1))
    D_inv_sqrt = np.linalg.inv(np.sqrt(D))
    normalized_affinity = D_inv_sqrt @ affinity_matrix @ D_inv_sqrt
    return normalized_affinity

def compute_relevance(eigenvectors, max_iter=100):
    n_samples, n_eigenvectors = eigenvectors.shape
    R_ek = np.full(n_eigenvectors, 0.5)
    mu = np.random.rand(2, n_eigenvectors)
    sigma = np.random.rand(2, n_eigenvectors)
    weights = np.full(2, 0.5)
    for iteration in range(max_iter):
        probabilities = np.zeros((n_samples, 2))
        for g in range(2):
            probabilities[:, g] = weights[g] * np.exp(-0.5 * np.sum(((eigenvectors - mu[g]) / sigma[g])**2, axis=1))
        probabilities /= probabilities.sum(axis=1, keepdims=True)
        for g in range(2):
            weights[g] = probabilities[:, g].mean()
            mu[g] = np.sum(probabilities[:, g][:, np.newaxis] * eigenvectors, axis=0) / probabilities[:, g].sum()
            sigma[g] = np.sqrt(
                np.sum(probabilities[:, g][:, np.newaxis] * (eigenvectors - mu[g])**2, axis=0) /
                probabilities[:, g].sum()
            )
    return R_ek

def weighted_eigenvectors(eigenvectors, relevances):
    weighted_vectors = eigenvectors * relevances
    return weighted_vectors

def extract_and_evaluate_eigenvectors_with_weights(affinity_matrix, num_eigenvectors=5):
    eigenvalues, eigenvectors = eigh(affinity_matrix)
    indices = np.argsort(eigenvalues)[-num_eigenvectors:]
    eigenvectors = eigenvectors[:, indices]
    relevances = compute_relevance(eigenvectors)
    weighted_data = weighted_eigenvectors(eigenvectors, relevances)
    return weighted_data, relevances

def cluster_with_gmm(data, max_clusters=10):
    best_bic = np.inf
    best_gmm = None
    for num_clusters in range(2, max_clusters + 1):
        gmm = GaussianMixture(n_components=num_clusters, covariance_type='full', random_state=42)
        gmm.fit(data)
        bic = gmm.bic(data)
        if bic < best_bic:
            best_bic = bic
            best_gmm = gmm
    return best_gmm, best_gmm.n_components

def spectral_clustering_algorithm_with_weights(data, sigma=1.5, num_eigenvectors=5):
    affinity_matrix = construct_gaussian_affinity_matrix(data, sigma=sigma)
    plt.figure(figsize=(6, 6))
    plt.imshow(affinity_matrix, cmap="hot")
    plt.title("Initial Affinity Matrix (Before Sorting)")
    plt.colorbar(label="Similarity")
    plt.show()

    normalized_affinity = normalize_affinity_matrix(affinity_matrix)
    weighted_data, relevances = extract_and_evaluate_eigenvectors_with_weights(
        normalized_affinity, num_eigenvectors
    )
    gmm_model, optimal_clusters = cluster_with_gmm(weighted_data)
    cluster_labels = gmm_model.predict(weighted_data)
    sorted_indices = np.argsort(cluster_labels)
    reordered_matrix = affinity_matrix[np.ix_(sorted_indices, sorted_indices)]
    plt.figure(figsize=(6, 6))
    plt.imshow(reordered_matrix, cmap="hot")
    plt.title("Reordered Affinity Matrix")
    plt.colorbar(label="Similarity")
    plt.show()
    return cluster_labels, optimal_clusters, relevances

