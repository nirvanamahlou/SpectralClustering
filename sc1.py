import numpy as np
import matplotlib.pyplot as plt
from sklearn.feature_extraction.image import img_to_graph
from sklearn.cluster import spectral_clustering
from skimage.data import coins
from skimage.transform import rescale
from scipy.ndimage import gaussian_filter
import time

orig_coins = coins()

smoothened_coins = gaussian_filter(orig_coins, sigma=2)
rescaled_coins = rescale(smoothened_coins, 0.2, mode="reflect", anti_aliasing=False)


graph = img_to_graph(rescaled_coins)

beta = 10
eps = 1e-6
graph.data = np.exp(-beta * graph.data / graph.data.std()) + eps

n_regions = 26
n_regions_plus = 3

for assign_labels in ("kmeans", "discretize", "cluster_qr"):
    t0 = time.time()
    labels = spectral_clustering(
        graph,
        n_clusters=(n_regions + n_regions_plus),
        eigen_tol=1e-7,
        assign_labels=assign_labels,
        random_state=42,
    )
    t1 = time.time()

    labels = labels.reshape(rescaled_coins.shape)


    plt.figure(figsize=(8, 8))
    plt.imshow(rescaled_coins, cmap=plt.cm.gray)
    plt.xticks(())
    plt.yticks(())
    title = f"Spectral clustering: {assign_labels}, {t1 - t0:.2f}s"
    plt.title(title)
    print(title)


    for l in range(n_regions):
        color = plt.cm.nipy_spectral((l + 4) / float(n_regions + 4))
        plt.contour(labels == l, colors=[color])

plt.show()

import numpy as np
import matplotlib.pyplot as plt
from sklearn.feature_extraction.image import img_to_graph
from sklearn.cluster import spectral_clustering

l = 100
x, y = np.indices((l, l))

rect1 = (x > 10) & (x < 50) & (y > 15) & (y < 50)
rect2 = (x > 30) & (x < 70) & (y > 30) & (y < 80)
ellipse1 = ((x - 40) / 15) ** 2 + ((y - 40) / 20) ** 2 < 1
ellipse2 = ((x - 60) / 20) ** 2 + ((y - 70) / 15) ** 2 < 1

img = rect1 + rect2 + ellipse1 + ellipse2
mask = img.astype(bool)
img = img.astype(float)

img += 1 + 0.5 * np.random.randn(*img.shape)

graph = img_to_graph(img, mask=mask)
graph.data = np.exp(-graph.data / graph.data.std())

n_clusters = 6
labels = spectral_clustering(graph, n_clusters=n_clusters, eigen_solver='arpack')
label_im = -np.ones(mask.shape)
label_im[mask] = labels

plt.figure(figsize=(12, 6))

plt.subplot(1, 2, 1)
plt.title("Original Complex Image with Shapes")
plt.imshow(img, cmap="gray")
plt.axis("off")

plt.subplot(1, 2, 2)
plt.title("Segmented Image")
plt.imshow(label_im, cmap="viridis")
plt.axis("off")

